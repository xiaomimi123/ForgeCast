/** 离线 mock 分析：结构完整的 7 段 analysis.md，slug 填进标题，正文通用合规。不调 LLM。 */
export function mockAnalysis(slug: string, readme: string): string {
  const firstLine = (readme.split('\n').find((l) => l.trim()) ?? '').slice(0, 60)
  return `# ${slug} 商业化分析

## 一句话：这是给谁的什么
给中小老板的「${slug}」：一套可自部署的开源工具，换皮成自有品牌后按部署/定制收费。（离线 mock 分析，live 模式据 README 生成）

## 目标买家画像（主攻1个，备选2个）
- 主攻：需要该工具但不想付高价 SaaS、也没技术团队的中小商家/团队（1-5人）
- 备选1：做外包/接单的开发者（转手部署给客户）
- 备选2：垂直行业服务商

## 痛点清单（按付费意愿排序，每条注明"现状成本"）
1. 现在用通用工具或人工凑合，效率低（现状成本：每天额外若干小时）
2. 商用 SaaS 年费高，长期支出（现状成本：每年数千元）
3. 数据在第三方，不放心（现状成本：合规与迁移风险）

## 换皮方向建议
- 品牌名候选：${slug}-plus / 速用${slug} / ${slug}管家
- 砍：面向大团队的高级协作；留：核心功能与自部署
- 新增本土化：微信登录、国内支付或平台对接

## 定价建议
- 部署价：1999 元（含服务器配置指导）
- 定制起步价：5000 元
- 参照物：同类 SaaS 年费 6000-20000 元/年

## 钩子匹配（核心输出，直接喂给 M4）
- 副业型：适用度 中 ——「我部署了个${slug}，帮人装每单收一次钱」
- 信息差型：适用度 高 ——「别再买年费 SaaS 了，这套${slug}自部署成本很低」
- 接单故事型：适用度 高 ——「客户要个${slug}，我一天交付」
- 行业痛点型：适用度 高 ——「还在用老办法？这套${slug}直接降维」

## 风险
- 协议：确认源项目为可商用协议，不使用其商标与 Logo
- 竞品：小红书可能已有同类内容，差异化打垂直场景
- 交付：买家服务器环境不一，标准化 Docker 部署文档

（源 README 摘要：${firstLine}）
`
}
